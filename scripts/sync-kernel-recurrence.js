'use strict';

// Kernel plugins have no module loader. Bundle the existing pure task rules,
// rather than maintaining a second implementation of recurrence in kernel.js.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const files = [
    'src/task-horizon/main/task-runtime/50-task-model-and-repeat-utils.js',
    'src/task-horizon/main/task-runtime/50a-fsrs-runtime.js',
    'src/task-horizon/main/task-runtime/54-recurring-task-runtime.js',
    'src/task-horizon/main/20-api-and-runtime-services.js',
];
const sources = files.map(file => fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n'));
const functions = new Map();
for (const source of sources) {
    for (const match of source.matchAll(/^    function (__\w+)\(/gm)) {
        const end = source.indexOf('\n    }', match.index);
        if (end < 0) throw new Error(`Unclosed function: ${match[1]}`);
        functions.set(match[1], source.slice(match.index, end + 6));
    }
}
const facade = {
    rulePatch: '__tmBuildTaskRepeatRuleMetaPatch',
    signature: '__tmGetTaskRepeatScheduleSignature',
    summary: '__tmGetTaskRepeatSummary',
    completionPlan: '__tmBuildTaskCompletionPlan',
    occurrenceId: '__tmGetTaskOccurrenceId',
    normalizeState: '__tmNormalizeTaskRepeatState',
    now: '__tmNowInChinaTimezoneIso',
    hasReminderIntent: '__tmSemanticHasReminderIntent',
};
const external = new Set(['__tmBuildFsrsReviewPatch', '__tmResolveTaskCompletedAtRaw', '__tmResolveTaskMarker']);
const included = new Map();
function include(name) {
    if (included.has(name) || external.has(name)) return;
    const source = functions.get(name);
    if (!source) throw new Error(`Missing recurrence dependency: ${name}`);
    included.set(name, source);
    for (const match of source.matchAll(/\b(__\w+)\s*\(/g)) include(match[1]);
}
Object.values(facade).forEach(include);
const constants = ['__tmMonthRepeatCore', '__TM_LUNAR_MONTH_TEXT_MAP', '__TM_LUNAR_INFO_1900_2049', '__tmChineseCalendarFormatter', '__TM_CHINA_TZ_OFFSET_MINUTES', '__TM_CHINA_TZ_SUFFIX'];
const declarations = constants.map(name => {
    for (const source of sources) {
        const match = new RegExp(`^    (?:const|let) ${name} = [\\s\\S]*?;`, 'm').exec(source);
        if (match) return match[0];
    }
    throw new Error(`Missing recurrence constant: ${name}`);
});
include('__createMonthRepeatCore');
const begin = '    /* generated task recurrence: begin */';
const end = '    /* generated task recurrence: end */';
const fsrsVendor = fs.readFileSync(path.join(root, 'src/task-horizon/vendor/ts-fsrs-5.4.1.umd.js'), 'utf8').replace(/\r\n/g, '\n').replace(/[ \t]+$/gm, '');
const bundle = `${begin}
    // Generated by scripts/sync-kernel-recurrence.js. Edit the task runtime sources.
    const TaskRecurrence = (() => {
    // Keep the vendored runtime local to this adapter, including its MIT notice.
    const globalThis = { FSRS: (() => {
        const exports = {};
        const module = { exports };
${fsrsVendor}
        return module.exports;
    })() };
${Array.from(included.values()).join('\n\n')}
${declarations.join('\n')}
    const __tmResolveTaskCompletedAtRaw = task => task.taskCompleteAt || task.task_complete_at || '';
    const __tmResolveTaskMarker = task => TaskStatus.fromMarkdown(task.markdown);
    const __tmBuildFsrsReviewPatch = () => { throw new Error('FSRS 评分请使用任务详情中的复习入口'); };
    return Object.freeze({ ${Object.entries(facade).map(([key, name]) => `${key}: ${name}`).join(', ')} });
    })();
${end}`;
const target = path.join(root, 'kernel.js');
const current = fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
const first = current.indexOf(begin), last = current.indexOf(end, first);
const updated = first >= 0 && last >= 0
    ? current.slice(0, first) + bundle + current.slice(last + end.length)
    : current.replace('    const TaskStatus = createTaskStatusRules();', `    const TaskStatus = createTaskStatusRules();\n\n${bundle}`);
if (process.argv.includes('--check')) {
    if (current !== updated) throw new Error('Kernel recurrence bundle is stale; run node scripts/sync-kernel-recurrence.js');
} else if (current !== updated) fs.writeFileSync(target, updated);
console.log(`kernel recurrence bundle ${process.argv.includes('--check') ? 'verified' : 'synchronized'} (${included.size} shared functions)`);
